// `resolveJsonModule` + a data file inside a dependency: a bare `*.json`
// specifier goes through the ordinary `node_modules` walk, not just `baseUrl`.
// `data-pkg` publishes no `exports` map, so `lib/well-known/services.json` is
// reachable at its real path — the shape the outline app imports out of
// nodemailer. Unresolved, this line is TS2307.
import services from "data-pkg/lib/well-known/services.json";
// The package's own declarations still resolve the normal way.
import { version } from "data-pkg";

// tsc synthesizes a structural type for the JSON; ztsc types it opaquely as
// `any` (the documented under-report), so the case only asserts reads that
// type-check under both.
const host: string = services.smtp.host;
export const label: string = version + host;
